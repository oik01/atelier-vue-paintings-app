// Dynamically register all 231 catalogue frames onto FRAME_PROFILES as non-enumerable properties
// so FRAME_PROFILES[frameId] and `frameId in FRAME_PROFILES` work for all 231 frames while
// Object.keys(FRAME_PROFILES) preserves the 6 canonical keys for legacy partner-quote loops.
for (const fwFrame of FINERWORKS_ALL_231_FRAMES) {
  if (!(fwFrame.profileId in FRAME_PROFILES)) {
    const profileSpec: FrameProfileSpec = {
      id: fwFrame.profileId,
      name: fwFrame.name,
      materialDescription: fwFrame.materialDescription,
      mouldingWidthInches: fwFrame.thicknessInches,
      depthInches: fwFrame.depthInches,
      primaryHex: fwFrame.primaryHex,
      secondaryHex: fwFrame.secondaryHex,
      highlightHex: fwFrame.highlightHex,
      isFloatFrame: fwFrame.isFloatFrame,
      priceMultiplier: Number(Math.max(1.18, 1 + (fwFrame.startingPriceUsd || 24) / 75).toFixed(2)),
      sku: fwFrame.sku,
      manufacturerId: fwFrame.manufacturerId,
      collectionId: fwFrame.collectionId,
      collectionName: fwFrame.collectionName,
      collectionSlug: fwFrame.collectionSlug,
      categoryGroup: fwFrame.categoryGroup,
      cornerImageUrl: fwFrame.cornerImageUrl,
      remoteCornerImageUrl: fwFrame.remoteCornerImageUrl,
      profileImageUrl: fwFrame.profileImageUrl,
      collectionImageUrl: fwFrame.collectionImageUrl,
      mouldingProfileStyle: fwFrame.mouldingProfileStyle,
    };
    Object.defineProperty(FRAME_PROFILES, fwFrame.profileId, {
      value: profileSpec,
      enumerable: false,
      configurable: true,
      writable: true,
    });
  }
}

